# Refresh the anchor index inside references/PROJECT_MAP.md.
#
#   powershell -ExecutionPolicy Bypass -File .opencode\skills\anaise\scripts\map.ps1
#
# The prose above the <!-- map:begin --> marker is hand written and is left
# alone. Only the generated block between the markers is replaced, so the line
# numbers and symbol list stay honest after a refactor. Nothing here touches the
# source or the build.

param(
    [string]$Source = 'src\main.cpp',
    [string]$Map = ''
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
if (-not $Map) {
    $Map = Join-Path $PSScriptRoot '..\references\PROJECT_MAP.md'
}
$Map = [System.IO.Path]::GetFullPath($Map)
$path = Join-Path $root $Source
if (-not (Test-Path $path)) { throw "no such source file: $path" }

$lines = [System.IO.File]::ReadAllLines($path)
$out = New-Object System.Collections.Generic.List[string]
$out.Add('<!-- generated by scripts/map.ps1; do not edit by hand -->')
$out.Add('')
$out.Add('### Sections in `' + ($Source -replace '\\', '/') + '`')
$out.Add('')
$out.Add('```')

# Section banners: "// ---------------- bethelament" at any indent.
$sectionPattern = '^\s*//\s*-{3,}\s*(.+?)\s*$'
for ($i = 0; $i -lt $lines.Count; $i++) {
    $m = [regex]::Match($lines[$i], $sectionPattern)
    if ($m.Success) {
        $title = $m.Groups[1].Value
        $prev = if ($i -gt 0) { $lines[$i - 1].Trim() } else { '' }
        if ($prev.StartsWith('//') -and $prev -notmatch '-{3,}') { $title = "$prev $title" }
        $out.Add(('L{0,-5} {1}' -f ($i + 1), $title))
    }
}
$out.Add('```')
$out.Add('')
$out.Add('### Symbols')
$out.Add('')
$out.Add('```')

# Types, free functions (column 0) and App methods (four spaces).
$typePattern = '^\s*(struct|class|enum)\s+\w+'
$freePattern = '^(?:static\s+)?[A-Za-z_][\w:<>,&*\s]*?\s([A-Za-z_]\w*)\(([^;]*)\)\s*\{'
$methodPattern = '^    [A-Za-z_][\w:<>,&*\s]*?\s([A-Za-z_]\w*)\(([^;]*)\)\s*(?:const\s*)?\{'
$constPattern = '^\s*constexpr\s+[^=;]+?([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*='
for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = $lines[$i]
    $hit = $null
    if ($line -match $typePattern) {
        $hit = ($line.Trim() -replace '\s*[{:].*$', '')
    } elseif ($line -match $freePattern) {
        $hit = $Matches[1] + '(' + ($Matches[2] -replace '\s+', ' ').Trim() + ')'
    } elseif ($line -match $methodPattern) {
        $hit = '  .' + $Matches[1] + '(' + ($Matches[2] -replace '\s+', ' ').Trim() + ')'
    } elseif ($line -match $constPattern) {
        $hit = 'constexpr ' + $Matches[1].Trim()
    }
    if ($hit) { $out.Add(('L{0,-5} {1}' -f ($i + 1), $hit)) }
}
$out.Add('```')

$begin = '<!-- map:begin -->'
$end = '<!-- map:end -->'
$text = [System.IO.File]::ReadAllText($Map)
$block = ($out -join "`n")
$pattern = [regex]::Escape($begin) + '[\s\S]*?' + [regex]::Escape($end)
$replacement = $begin + "`n" + $block + "`n" + $end
if ($text -match $pattern) {
    $text = [regex]::Replace($text, $pattern, $replacement.Replace('$', '$$'))
} else {
    $text = $text.TrimEnd() + "`n`n" + $replacement + "`n"
}
[System.IO.File]::WriteAllText($Map, $text)
Write-Host "Updated $Map from $Source ($($lines.Count) lines)."
